/* Translations of the TV app's texts. The TV's language picks them (English
 * for languages not listed). Messages from the shared core (banners, "Added
 * to favorites"...) are translated by the core itself. */
'use strict';

var LANG = String(navigator.language || 'en').slice(0, 2).toLowerCase();

/** The text in the TV's language. */
function T(en) {
    var table = I18N[LANG];
    return (table && table[en]) || en;
}

/** The text with {0}, {1}... replaced by the following arguments. */
function TF(en) {
    var s = T(en);
    for (var i = 1; i < arguments.length; i++) s = s.split('{' + (i - 1) + '}').join(String(arguments[i]));
    return s;
}

/** The remote-control help, in the TV's language. */
function helpText() {
    return (HELP_TEXT[LANG] || HELP_TEXT.en).concat(['', 'IPTV ' + (window.IPTV_VERSION || '')]).join('\n');
}

